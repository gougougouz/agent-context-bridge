"""Install the skill bundle into DSH / Codex / Claude skill directories."""

from __future__ import annotations

import os
import shutil
import sys
from pathlib import Path

from .model import AGENT_LABELS
from .i18n import t
from .util import WINDOWS, atomic_write_text

SKILL_NAME = "agent-context-bridge"

LAUNCHER_CMD = """@echo off
rem agentlink launcher generated by `agentlink install` - safe to regenerate.
setlocal
set "PYTHON={python}"
set "AGENTLINK_SRC={src}"
if not exist "%PYTHON%" set "PYTHON=python"
if not exist "%AGENTLINK_SRC%\\agentlink" (
  rem the tool moved or was uninstalled: fall back to whatever is on PATH
  where agentlink >nul 2>nul
  if errorlevel 1 (
    echo agentlink: installation not found at "%AGENTLINK_SRC%" 1>&2
    echo   reinstall: irm https://raw.githubusercontent.com/gougougouz/agent-context-bridge/main/install.ps1 ^| iex 1>&2
    exit /b 1
  )
  agentlink %*
  exit /b %ERRORLEVEL%
)
set "PYTHONPATH=%AGENTLINK_SRC%;%PYTHONPATH%"
"%PYTHON%" -m agentlink %*
exit /b %ERRORLEVEL%
"""

LAUNCHER_SH = """#!/usr/bin/env sh
# agentlink launcher generated by `agentlink install` - safe to regenerate.
if [ -d "{src}/agentlink" ]; then
  PYTHONPATH="{src}${{PYTHONPATH:+:$PYTHONPATH}}" exec "{python}" -m agentlink "$@"
fi
if command -v agentlink >/dev/null 2>&1; then
  exec agentlink "$@"
fi
echo "agentlink: installation not found at {src}" >&2
echo "  reinstall: curl -fsSL https://raw.githubusercontent.com/gougougouz/agent-context-bridge/main/install.sh | bash" >&2
exit 1
"""


def repo_root() -> Path:
    """The checkout that contains src/agentlink (works for editable and source runs)."""
    return Path(__file__).resolve().parents[2]


def python_exe() -> Path:
    return Path(sys.executable)


def skill_home(agent: str) -> Path:
    home = Path(os.path.expanduser("~"))
    if agent == "dsh":
        return Path(os.environ.get("DSH_HOME") or home / ".dsh") / "skills"
    if agent == "codex":
        return Path(os.environ.get("CODEX_HOME") or home / ".codex") / "skills"
    if agent == "claude":
        return Path(os.environ.get("CLAUDE_CONFIG_DIR") or home / ".claude") / "skills"
    raise SystemExit(f"未知 agent: {agent}")


def build_launcher(target_dir: Path) -> list[str]:
    src = repo_root() / "src"
    py = python_exe()
    written = []
    if WINDOWS:
        script = target_dir / "agentlink.cmd"
        script.write_text(LAUNCHER_CMD.format(python=py, src=src), encoding="utf-8")
        written.append(str(script))
    script = target_dir / "agentlink.sh"
    atomic_write_text(script, LAUNCHER_SH.format(python=py.as_posix(), src=src.as_posix()))
    if not WINDOWS:
        os.chmod(script, 0o755)
    written.append(str(script))
    return written


def local_md(agent: str, target_dir: Path) -> str:
    py = python_exe()
    launcher = target_dir / ("agentlink.cmd" if WINDOWS else "agentlink.sh")
    return f"""# LOCAL - 本机安装信息（由 `agentlink install` 生成，可重复生成）

- 技能名：`{SKILL_NAME}`
- 安装目标：{AGENT_LABELS.get(agent, agent)} → `{target_dir}`
- 源码仓库：`{repo_root()}`
- Python：`{py}`
- 启动器：`"{launcher}"`
- 状态目录（项目内）：`<项目根>/.agentlink/`

## 直接可用的命令

```
"{launcher}" status
"{launcher}" sync
"{launcher}" brief
```

如果 `agentlink` 已经在 PATH 上，上面的绝对路径版和 `agentlink` 等价。
"""


def install(agents: list[str], force: bool = True) -> list[dict]:
    root = repo_root()
    skill_src = root / "SKILL.md"
    if not skill_src.exists():
        raise SystemExit(f"仓库里缺少 SKILL.md：{skill_src}")
    results = []
    for agent in agents:
        target = skill_home(agent) / SKILL_NAME
        target.mkdir(parents=True, exist_ok=True)
        shutil.copy2(skill_src, target / "SKILL.md")
        for extra in ("README.md", "README.zh-CN.md", "INSTALL.md"):
            doc = root / extra
            if doc.exists():
                shutil.copy2(doc, target / extra)
        docs_src = root / "docs"
        if docs_src.is_dir():  # README links into docs/, keep them valid after copying
            for doc in sorted(docs_src.glob("*.md")):
                (target / "docs").mkdir(exist_ok=True)
                shutil.copy2(doc, target / "docs" / doc.name)
        launchers = build_launcher(target)
        atomic_write_text(target / "LOCAL.md", local_md(agent, target))
        for extra in ("agentlink.cmd", "agentlink.sh"):
            p = target / extra
            if p.exists() and not WINDOWS and extra.endswith(".cmd"):
                p.unlink()
        results.append({"agent": agent, "dir": str(target), "files": launchers + ["SKILL.md", "LOCAL.md"]})
    return results


MARK_BEGIN = "<!-- agentlink:begin -->"
MARK_END = "<!-- agentlink:end -->"

POINTER_FILES = ("AGENTS.md", "CLAUDE.md")


def pointer_block(synced_at: str) -> str:
    return f"""{MARK_BEGIN}
## 项目上下文（agentlink 自动维护，请勿手改此段）

本项目在 DSH / Codex / Claude 之间切换过。**接手任何任务前**，先运行 `agentlink brief`
（或在聊天里说"接着之前的做"），取最新上下文：对话结论、待办、最近改动。
`.agentlink/context.md` 是上一次的速览，仅在不能执行命令时才读它。

最近一次同步：{synced_at or "尚未同步"}
{MARK_END}
"""


def write_pointers(root: Path, synced_at: str, files=POINTER_FILES) -> list[str]:
    """Insert (or refresh) the pointer block so a fresh agent notices the context."""
    block = pointer_block(synced_at)
    touched = []
    for name in files:
        path = root / name
        text = path.read_text(encoding="utf-8") if path.exists() else ""
        if MARK_BEGIN in text and MARK_END in text:
            start = text.index(MARK_BEGIN)
            end = text.index(MARK_END) + len(MARK_END)
            new = text[:start] + block.rstrip("\n") + text[end:]
        else:
            sep = "" if not text else ("\n" if text.endswith("\n") else "\n\n")
            new = text + sep + block
        atomic_write_text(path, new)
        touched.append(str(path))
    return touched


def remove_pointers(root: Path, files=POINTER_FILES) -> list[str]:
    removed = []
    for name in files:
        path = root / name
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        if MARK_BEGIN not in text:
            continue
        start = text.index(MARK_BEGIN)
        end = text.index(MARK_END) + len(MARK_END)
        new = (text[:start].rstrip("\n") + "\n" + text[end:].lstrip("\n")).strip() + "\n"
        if new.strip():
            atomic_write_text(path, new)
        else:
            path.unlink()
        removed.append(str(path))
    return removed


def ensure_path_entry(directory: Path, scope: str = "user") -> bool:
    """Append a directory to the Windows user PATH (idempotent)."""
    if not WINDOWS:
        return False
    try:
        import winreg  # type: ignore

        key = winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE)
        try:
            current, _ = winreg.QueryValueEx(key, "Path")
        except FileNotFoundError:
            current = ""
        parts = [p for p in current.split(";") if p]
        if any(os.path.normcase(p.rstrip("\\")) == os.path.normcase(str(directory).rstrip("\\")) for p in parts):
            winreg.CloseKey(key)
            return False
        parts.append(str(directory))
        winreg.SetValueEx(key, "Path", 0, winreg.REG_EXPAND_SZ, ";".join(parts))
        winreg.CloseKey(key)
        return True
    except OSError:
        return False